require('dotenv').config();
const express = require('express');
const cors = require('cors');
const { randomUUID } = require('node:crypto');
const { store, createRun, getRun, updateRun, saveAction } = require('./store');
const { runAgents } = require('./agents');
const { generateGoalPlan } = require('./openaiAdapter');
const { generateBusinessAnalysis } = require('./codebuddyAdapter');

const app = express();
app.use(cors({ origin: process.env.FRONTEND_ORIGIN || true }));
app.use(express.json({ limit: '100kb' }));
app.use((req, res, next) => {
  const requestId = randomUUID();
  req.requestId = requestId;
  res.setHeader('X-Request-ID', requestId);
  if (req.path.startsWith('/api/')) {
    console.info(JSON.stringify({ event: 'api.request', requestId, method: req.method, endpoint: req.path }));
    res.on('finish', () => console.info(JSON.stringify({ event: 'api.response', requestId, method: req.method, endpoint: req.path, status: res.statusCode })));
  }
  next();
});

app.get('/api/health', (_req, res) => res.json({
  ok: true,
  persistence: store.mode,
  aiProvider: process.env.AGENT_PROVIDER || 'codebuddy',
  openaiKeyConfigured: Boolean(process.env.OPENAI_API_KEY?.trim()),
  revision: process.env.RENDER_GIT_COMMIT || process.env.SOURCE_VERSION || null
}));

app.post('/api/goal', async (req, res, next) => {
  try {
    const { goal, budget, currency, productDescription, targetCustomer, provider } = req.body || {};
    if (typeof goal !== 'string' || !goal.trim()) return res.status(400).json({ error: 'goal is required and must be a non-empty string' });
    if (budget !== undefined && (!Number.isFinite(Number(budget)) || Number(budget) < 0)) return res.status(400).json({ error: 'budget must be a non-negative number' });
    const requestedProvider = provider || process.env.AGENT_PROVIDER || 'codebuddy';
    if (!['mock', 'openai', 'codebuddy'].includes(requestedProvider)) return res.status(400).json({ error: 'provider must be openai, codebuddy, or mock' });
    const keyConfigured = Boolean(process.env.OPENAI_API_KEY?.trim());
    console.info(JSON.stringify({ event: 'goal.provider_selected', requestId: req.requestId, provider: requestedProvider, openAIKeyConfigured: keyConfigured }));
    if (requestedProvider === 'openai' && !keyConfigured) {
      console.error(JSON.stringify({ event: 'openai.failed', requestId: req.requestId, reason: 'missing_api_key' }));
      return res.status(503).json({ error: 'OPENAI_API_KEY is not configured on the backend.' });
    }
    const runId = randomUUID();
    const input = { goal: goal.trim(), budget: budget === undefined ? 500 : Number(budget), currency, productDescription, targetCustomer };
    const initial = { runId, goal: input.goal, status: 'running', agents: Object.fromEntries(['businessAnalyst', 'growth', 'teamBuilder', 'operations', 'feedback'].map((name) => [name, { status: 'pending' }])), input };
    let output;
    let agentProvider = requestedProvider;
    let providerNote = requestedProvider === 'openai'
      ? 'All planning agents generated by OpenAI.'
      : requestedProvider === 'codebuddy'
        ? 'Business Analyst generated with CodeBuddy; remaining agents use deterministic mock logic.'
        : 'Deterministic mock agents used by explicit request.';
    let codebuddySessionId = null;
    try {
      if (requestedProvider === 'openai') console.info(JSON.stringify({ event: 'openai.request_started', requestId: req.requestId, model: process.env.OPENAI_MODEL || 'gpt-4.1-mini' }));
      output = requestedProvider === 'openai' ? await generateGoalPlan(input) : runAgents(input);
      if (requestedProvider === 'openai') console.info(JSON.stringify({ event: 'openai.request_succeeded', requestId: req.requestId }));
    } catch (error) {
      const providerError = error.error && typeof error.error === 'object' ? error.error : {};
      const safeErrorMessage = String(providerError.message || error.message || '')
        .replace(/\bsk-[A-Za-z0-9_-]{10,}\b/g, '[REDACTED]')
        .replace(/Bearer\s+\S+/gi, 'Bearer [REDACTED]')
        .slice(0, 1000);
      console.error(JSON.stringify({
        event: `${requestedProvider}.failed`,
        requestId: req.requestId,
        openAIRequestId: error.requestID || null,
        httpStatus: error.status || null,
        message: safeErrorMessage,
        type: providerError.type || error.type || error.constructor?.name || 'Error',
        code: providerError.code || error.code || null,
        param: providerError.param || null,
        model: process.env.OPENAI_MODEL || 'gpt-4.1-mini'
      }));
      const status = error.status === 429 ? 429 : 502;
      const message = error.status === 429
        ? 'OpenAI quota or rate limit reached. Check API billing and limits, then try again.'
        : error.status === 401
          ? 'OpenAI rejected the backend API key. Check OPENAI_API_KEY in Render.'
          : `OpenAI request failed${error.status ? ` (HTTP ${error.status})` : ''}. Check the backend logs using the X-Request-ID response header.`;
      return res.status(status).json({ error: message });
    }
    if (requestedProvider === 'codebuddy') {
      try {
        const ai = await generateBusinessAnalysis(input);
        output.agents.businessAnalyst.result = ai.result;
        codebuddySessionId = ai.sessionId || null;
      } catch (error) {
        agentProvider = 'mock_fallback';
        providerNote = 'CodeBuddy was requested but failed or returned invalid data; deterministic mock agents were used.';
        console.error('CodeBuddy provider failed:', error.message);
      }
    }
    await createRun(initial);
    const recommendation = { ...output.recommendation, actionId: `improve-conversion-${runId}` };
    output.agents.feedback.result = recommendation;
    const finalRun = await updateRun(runId, { status: 'awaiting_approval', provider: agentProvider, providerNote, codebuddySessionId: codebuddySessionId || output.codebuddySessionId || null, agents: output.agents, results: output.agents, recommendation });
    await saveAction({ runId, actionId: recommendation.actionId, type: 'recommendation', status: 'pending', recommendation });
    return res.status(201).json({ runId, status: finalRun.status, provider: agentProvider, providerNote, statusUrl: `/api/status?runId=${runId}`, resultsUrl: `/api/results?runId=${runId}`, recommendation });
  } catch (error) { return next(error); }
});

app.get('/api/status', async (req, res, next) => {
  try {
    if (!req.query.runId) return res.status(400).json({ error: 'runId query parameter is required' });
    const run = await getRun(req.query.runId);
    if (!run) return res.status(404).json({ error: 'run not found' });
    return res.json({ runId: run.runId, status: run.status, provider: run.provider || 'mock', providerNote: run.providerNote || null, agents: run.agents, updatedAt: run.updatedAt });
  } catch (error) { return next(error); }
});

app.get('/api/results', async (req, res, next) => {
  try {
    if (!req.query.runId) return res.status(400).json({ error: 'runId query parameter is required' });
    const run = await getRun(req.query.runId);
    if (!run) return res.status(404).json({ error: 'run not found' });
    return res.json({ runId: run.runId, goal: run.goal, provider: run.provider || 'mock', providerNote: run.providerNote || null, results: run.results || {}, recommendation: run.recommendation || null });
  } catch (error) { return next(error); }
});

app.post('/api/approve', async (req, res, next) => {
  try {
    const { runId, actionId, approved } = req.body || {};
    if (!runId || !actionId || typeof approved !== 'boolean') return res.status(400).json({ error: 'runId, actionId, and boolean approved are required' });
    const run = await getRun(runId);
    if (!run) return res.status(404).json({ error: 'run not found' });
    if (run.recommendation?.actionId !== actionId) return res.status(404).json({ error: 'action not found for this run' });
    const status = approved ? 'approved' : 'rejected';
    await saveAction({ runId, actionId, type: 'recommendation', status, approvedAt: new Date().toISOString() });
    await updateRun(runId, { status: approved ? 'approved' : 'rejected', approval: { actionId, approved, decidedAt: new Date().toISOString() } });
    return res.json({ runId, actionId, status, message: approved ? 'Recommendation approved. No external action was executed.' : 'Recommendation rejected.' });
  } catch (error) { return next(error); }
});

app.use((error, _req, res, _next) => {
  console.error(error);
  return res.status(500).json({ error: 'internal server error' });
});

const port = Number(process.env.PORT) || 3000;
if (require.main === module) app.listen(port, () => console.log(`OnlySkills API listening on http://localhost:${port} (${store.mode} mode)`));
module.exports = app;
